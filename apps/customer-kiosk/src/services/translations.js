export function numberToTamilWords(num) {
  const map = {
    1000: 'ஆயிரம்',
    2000: 'இரண்டாயிரம்',
    5000: 'ஐந்தாயிரம்',
    10000: 'பத்தாயிரம்',
  }
  return map[num] || num
}

